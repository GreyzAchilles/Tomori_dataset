SELF_GROUP = "self"


def main():
    rng = random.Random(42)
    samples = []
    i = 0
    for grp, questions, answer in FACTS:
        for q in questions:
            i += 1
            samples.append({
                "instruction": q, "input": "", "output": answer,
                "source": f"identity_qa_{i:04d}", "text_ja": None, "_grp": grp,
            })
    rng.shuffle(samples)
    n_val = max(1, round(len(samples) * 0.05))
    val, train = samples[:n_val], samples[n_val:]

    def stamp(subset):
        pool = [s for s in subset if s["_grp"] != SELF_GROUP]
        k = max(1, round(len(subset) * 0.2))
        for s in pool[:k]:
            s["system"] = SYSTEM_CARD

    stamp(train)
    stamp(val)

    OUT.mkdir(parents=True, exist_ok=True)
    for name, subset in (("train", train), ("val", val)):
        with (OUT / f"{name}.jsonl").open("w", encoding="utf-8") as f:
            for s in subset:
                rec = {k: v for k, v in s.items() if not k.startswith("_")}
                f.write(json.dumps(rec, ensure_ascii=False) + "\n")

    answers = {a for _, _, a in FACTS}
    L = [len(a) for a in answers]
    n_self = sum(1 for g, _, _ in FACTS if g == SELF_GROUP)
    grp_cnt = Counter(g for g, _, _ in FACTS)
    n_card = sum("system" in s for s in samples)
    lines = [
        "# identity 数据集构造报告（v2，2026-10-14）", "",
        "## v1 → v2 修订",
        "",
        "- 答案瘦身：长度中位 46 → "
        f"**{statistics.median(L):.0f}**（事实完整保留，只修剪装饰）",
        f"- 问法增广：**{len(FACTS)} 个事实 × 多问法 = {len(samples)} 条 QA**"
        f"（平均 {len(samples)/len(FACTS):.1f} 种问法/事实；3 epoch ≈ 每事实 "
        f"{3 * len(samples) / len(FACTS):.0f} 次曝光）",
        "- 词内结巴：功能词上引入（我……我是/不……不是），事实 token（日期/人名/数字）保持完整",
        "",
        "## 构成",
        "",
        f"- 划分：train {len(train)} / val {len(val)}（95:5，seed=42）",
        f"- system：{n_card} 条人格卡（整体 {n_card/len(samples):.0%}）；"
        f"self 组 {n_self} 事实的样本 100% 裸（spec §2.3）",
        "",
        "| 组别 | 事实数 |", "| --- | --- |",
    ]
    for g, n in grp_cnt.most_common():
        lines.append(f"| {g} | {n} |")
    lines += [
        "",
        f"答案长度分布（去重后 {len(answers)} 条）：中位 {statistics.median(L):.0f} / "
        f"p90 {sorted(L)[int(len(L)*0.9)]} / 最长 {max(L)}",
        "",
        "依据：99_logs/external_corpus_comparison_20261014.md + 微调原理复核"
        "（知识召回主杠杆是问法增广而非答案长度；答案长度影响风格先验与 loss 集中度）。",
    ]
    (ROOT / "99_logs" / "identity_build_20261014_v2.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"facts {len(FACTS)} -> QA {len(samples)} (train {len(train)} / val {len(val)}); "
          f"cards {n_card}; answer median {statistics.median(L):.0f} chars")


if __name__ == "__main__":
    main()
